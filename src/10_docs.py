"""Generate docs/indicator_definitions.md and docs/data_dictionary.md from the database so that
the documentation cannot drift from the definitions that the views actually use.

Run: python -I src/10_docs.py
"""
from pathlib import Path
import duckdb

ROOT = Path(__file__).resolve().parent.parent
con = duckdb.connect(str(ROOT / "data" / "cuyahoga.duckdb"), read_only=True)

ind = con.execute("SELECT * FROM indicator_def ORDER BY theme, indicator_id").df()
cells = con.execute("""SELECT c.indicator_id, c.role, string_agg(c.variable || ' ' || v.label, '; ' ORDER BY c.variable) AS cells
                       FROM indicator_cell c JOIN dim_variable v USING (variable) GROUP BY ALL""").df()
rel = con.execute("""SELECT indicator_id,
        count(*) FILTER (WHERE reliability = 'high') AS high,
        count(*) FILTER (WHERE reliability = 'medium') AS medium,
        count(*) FILTER (WHERE reliability = 'low') AS low,
        count(*) FILTER (WHERE reliability IN ('unavailable', 'no_moe', 'zero_estimate')) AS other
        FROM v_indicator WHERE geo_level = 'tract' AND vintage = '2020-2024' GROUP BY 1""").df().set_index("indicator_id")

out = ["# Indicator definitions", "",
       "Generated by `src/10_docs.py` from the `indicator_def` and `indicator_cell` tables. The last four columns count",
       "the 428 tracts of the 2020-2024 vintage by the reliability class of the estimate (see",
       "[technical_standards.md](technical_standards.md)); other = unavailable, zero estimate or no margin of error.", "",
       "| Indicator | Theme | Unit | Higher means | Definition | high | medium | low | other |", "|---|---|---|---|---|---|---|---|---|"]
for r in ind.itertuples():
    k = rel.loc[r.indicator_id]
    out.append(f"| `{r.indicator_id}` {r.name} | {r.theme} | {r.unit} | {r.higher_is} | {r.definition} | {k.high} | {k.medium} | {k.low} | {k.other} |")
out += ["", "## Cells used", ""]
for r in ind.itertuples():
    out.append(f"**{r.indicator_id}**")
    for c in cells[cells.indicator_id == r.indicator_id].itertuples():
        out.append(f"- {c.role}: {c.cells}")
    out.append("")
(ROOT / "docs" / "indicator_definitions.md").write_text("\n".join(out), encoding="utf-8")

dd = ["# Data dictionary", "", "## Tables", ""]
for (t,) in con.execute("SELECT table_name FROM duckdb_tables() ORDER BY table_name").fetchall():
    n = con.execute(f"SELECT count(*) FROM {t}").fetchone()[0]
    dd.append(f"### {t} ({n} rows)")
    dd.append("")
    dd.append("| Column | Type |")
    dd.append("|---|---|")
    for col, typ in con.execute("SELECT column_name, data_type FROM duckdb_columns() WHERE table_name = ? ORDER BY column_index", [t]).fetchall():
        dd.append(f"| {col} | {typ} |")
    dd.append("")
dd += ["## Views", ""]
for (v,) in con.execute("SELECT view_name FROM duckdb_views() WHERE NOT internal ORDER BY view_name").fetchall():
    cols = con.execute("SELECT column_name FROM duckdb_columns() WHERE table_name = ? ORDER BY column_index", [v]).fetchall()
    dd.append(f"- `{v}`: " + ", ".join(c[0] for c in cols))
(ROOT / "docs" / "data_dictionary.md").write_text("\n".join(dd) + "\n", encoding="utf-8")
print("wrote docs/indicator_definitions.md and docs/data_dictionary.md")
